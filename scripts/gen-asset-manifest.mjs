// Lists every file the game streams in (characters, motions, kit models, item icons) with its size,
// so the start screen can download them all before play. Re-run after adding assets:
//   node scripts/gen-asset-manifest.mjs
// tests/unit/assets.test.ts fails when the manifest is out of date.
import {readdir, readFile, stat, writeFile} from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, {withFileTypes: true})) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...await walk(full));
    else if (/\.(ts|tsx)$/.test(entry.name)) out.push(full);
  }
  return out;
}
const exists = async p => stat(p).then(() => true, () => false);

export async function collectAssets() {
  const sources = await Promise.all((await walk(path.join(root, 'game'))).map(f => readFile(f, 'utf8')));
  const text = sources.join('\n');
  const models = new Set(text.match(/(?:nature-kit|furniture-kit|food-kit|fantasy-town)\/[A-Za-z0-9_-]+/g) ?? []);
  // Names the code builds at runtime.
  for (const c of ['red', 'yellow', 'purple']) for (const v of 'ABC') models.add(`nature-kit/flower_${c}${v}`);
  for (const v of 'ABCDE') models.add(`nature-kit/rock_large${v}`);
  for (const m of text.matchAll(/model: '((?:crop|crops)_[A-Za-z0-9_]+)'/g)) models.add(`nature-kit/${m[1]}`);
  const urls = [];
  for (const m of [...models].sort()) if (await exists(path.join(root, 'public/kit', `${m}.glb`))) urls.push(`/kit/${m}.glb`);
  for (const m of text.matchAll(/'(\/characters\/[A-Za-z0-9_.-]+\.(?:vrm|glb))'/g)) urls.push(m[1]);
  for (const f of (await readdir(path.join(root, 'public/kit/icons'))).sort()) urls.push(`/kit/icons/${f}`);
  const files = [];
  for (const url of [...new Set(urls)]) files.push({url, bytes: (await stat(path.join(root, 'public', url))).size});
  return files;
}

if (process.argv[1] && import.meta.url.endsWith(path.basename(process.argv[1]))) {
  const files = await collectAssets();
  const body = `// Generated by scripts/gen-asset-manifest.mjs. Do not edit by hand.\nexport const ASSET_MANIFEST: {url: string; bytes: number}[] = ${JSON.stringify(files, null, 1)};\n`;
  await writeFile(path.join(root, 'game/client/asset-manifest.ts'), body);
  console.log(`${files.length} files, ${(files.reduce((s, f) => s + f.bytes, 0) / 1048576).toFixed(1)} MB`);
}
