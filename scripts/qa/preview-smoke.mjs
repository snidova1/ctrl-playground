import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {chromium} from '@playwright/test';
const origin=process.env.CTRL_STAGING_ORIGIN;
assert(origin?.startsWith('https://ctrl-staging.'),'Staging origin required');
await mkdir('test-results',{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-dev-shm-usage']});
try{
 const page=await browser.newPage({viewport:{width:1440,height:960}});
 const errors=[],api=[],models=new Set(),assetFailures=[];
 page.on('response',r=>{if(r.url().includes('/assets/fantasy-town/')||r.url().includes('/plaza/build-kit/')){if(r.status()>=400)assetFailures.push(r.url());else if(r.url().endsWith('.glb'))models.add(r.url().split('/').at(-1));}});
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(new URL(r.url()).pathname.startsWith('/api/'))api.push(r.url());});
 const ready=()=>page.waitForFunction(()=>document.documentElement.dataset.ctrlVillageReady==='true'&&document.documentElement.dataset.ctrlHouseCount==='1',{},{timeout:60000});
 const saved=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('ctrl-habit-local-v1')));
 const response=await page.goto(`${origin}/preview`,{waitUntil:'domcontentloaded',timeout:60000});
 assert.equal(response.status(),200);
 await page.getByText('NO WALLET',{exact:true}).waitFor();
 await ready();await page.waitForTimeout(3000);
 assert.equal(await page.getByRole('alert').count(),0);
 assert.equal(await page.getByRole('navigation',{name:'Machine rooms'}).count(),0);
 const before=await saved();assert.equal(before.decor.length,4);
 await page.screenshot({path:'test-results/habit-before.png'});
 await page.getByRole('button',{name:'Edit home',exact:true}).click();
 await page.getByLabel('Roof shape',{exact:true}).selectOption('tall');
 await page.getByLabel('Wall style',{exact:true}).selectOption('timber');
 await page.getByRole('button',{name:'Terracotta roof',exact:true}).click();
 await page.getByRole('button',{name:'+ Bench',exact:true}).click();
 await page.getByLabel('Decoration x',{exact:true}).fill('6.5');
 await page.getByLabel('Decoration rotation',{exact:true}).fill('1.5');
 await page.getByLabel('Decoration scale',{exact:true}).fill('2.5');
 await page.waitForFunction(()=>{const d=JSON.parse(localStorage.getItem('ctrl-habit-local-v1'));return d.decor.length===5&&d.decor.at(-1).x===6.5&&d.decor.at(-1).scale===2.5&&d.house.roofColor==='#bd7356';});
 const modified=await saved();assert.equal(modified.house.tall,true);assert.equal(modified.house.timber,true);
 await ready();await page.waitForTimeout(2000);await page.screenshot({path:'test-results/habit-editor.png'});
 await page.getByRole('button',{name:'Done editing',exact:true}).click();
 await page.reload({waitUntil:'domcontentloaded'});await ready();await page.waitForTimeout(2000);
 assert.deepEqual(await saved(),modified,'House and decoration edits must survive reload');
 await page.screenshot({path:'test-results/wallet-free-preview.png'});
 await page.getByRole('button',{name:'Edit home',exact:true}).click();
 await page.getByLabel('Selected decoration',{exact:true}).selectOption(modified.decor.at(-1).id);
 await page.getByRole('button',{name:'Remove decoration',exact:true}).click();
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('ctrl-habit-local-v1')).decor.length===4);
 await page.reload({waitUntil:'domcontentloaded'});await ready();assert.equal((await saved()).decor.length,4);
 await page.setViewportSize({width:390,height:844});await page.waitForTimeout(1500);await page.screenshot({path:'test-results/habit-mobile.png'});
 assert(models.has('wall-door.glb'));assert(models.has('roof-high-gable.glb'));assert(models.has('bench.glb'));
 assert.deepEqual(assetFailures,[],'No missing models or textures');assert.deepEqual(api,[],'No wallet or personal-world APIs');assert.deepEqual(errors,[],'No browser runtime errors');
 await writeFile('test-results/preview-smoke.json',JSON.stringify({url:`${origin}/preview`,http:200,houseCount:1,houseCustomization:true,addMoveRotateResizeDelete:true,localPersistence:true,noWalletApiRequests:true,pageErrors:errors},null,2));
 console.log('Habit single-home customization and local persistence acceptance passed.');
}finally{await browser.close();}
